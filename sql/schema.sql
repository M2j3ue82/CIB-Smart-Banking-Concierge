-- CIB Banking Assistant: database schema (Supabase / PostgreSQL)
-- Run this once in the Supabase SQL editor.
-- The chat-memory table (n8n_chat_histories) is created automatically by the n8n Postgres Chat Memory node.

create extension if not exists vector with schema extensions;

-- 1) Knowledge base chunks (embedding size 3072 = gemini-embedding-001)
create table if not exists public.cib_documents (
  id bigserial primary key,
  content text,
  metadata jsonb,
  embedding vector(3072)
);

-- 2) Similarity search used by the n8n Supabase Vector Store node
create or replace function public.match_cib_documents (
  query_embedding vector(3072),
  match_count int default null,
  filter jsonb default '{}'
) returns table (
  id bigint,
  content text,
  metadata jsonb,
  similarity float
)
language plpgsql
as $$
#variable_conflict use_column
begin
  return query
  select
    id,
    content,
    metadata,
    1 - (cib_documents.embedding <=> query_embedding) as similarity
  from public.cib_documents
  where metadata @> filter
  order by cib_documents.embedding <=> query_embedding
  limit match_count;
end;
$$;

-- 3) Support tickets (ticket_no is generated by the database, e.g. CIB-000001)
create table if not exists public.cib_support_tickets (
  id bigserial primary key,
  ticket_no text generated always as ('CIB-' || lpad(id::text, 6, '0')) stored,
  customer_message text not null,
  category text,            -- card_lost | fraud | complaint | human_request | other
  priority text default 'normal',  -- high | normal
  status text default 'open',
  created_at timestamptz default now()
);

-- 4) Permissions: only the service role (used by n8n) can access these tables
grant usage on schema public to service_role;
grant all on all tables in schema public to service_role;
grant all on all sequences in schema public to service_role;
grant execute on all functions in schema public to service_role;

notify pgrst, 'reload schema';
